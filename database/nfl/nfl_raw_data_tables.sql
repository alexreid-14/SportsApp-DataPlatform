-- Player stats table
CREATE TABLE IF NOT EXISTS nfl_raw.player_stats (
    stat_id VARCHAR(50) PRIMARY KEY,
    game_id VARCHAR(20) NOT NULL,
    player_id VARCHAR(20) NOT NULL,
    team VARCHAR(10),
    player_name VARCHAR(100),
    position VARCHAR(10),
    passing_attempts INTEGER,
    passing_completions INTEGER,
    passing_yards INTEGER,
    passing_touchdowns INTEGER,
    passing_interceptions INTEGER,
    passing_sacks INTEGER,
    passing_sack_yards INTEGER,
    passing_long INTEGER,
    passing_rating DECIMAL(5,2),
    rushing_attempts INTEGER,
    rushing_yards INTEGER,
    rushing_touchdowns INTEGER,
    rushing_long INTEGER,
    receiving_targets INTEGER,
    receiving_receptions INTEGER,
    receiving_yards INTEGER,
    receiving_touchdowns INTEGER,
    receiving_long INTEGER,
    fumbles INTEGER,
    fumbles_lost INTEGER,
    interceptions INTEGER,
    interception_yards INTEGER,
    interception_touchdowns INTEGER,
    passes_defended INTEGER,
    tackles INTEGER,
    tackles_assisted INTEGER,
    sacks INTEGER,
    sack_yards INTEGER,
    tackles_for_loss INTEGER,
    tackles_for_loss_yards INTEGER,
    quarterback_hits INTEGER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (game_id) REFERENCES nfl_raw.games(game_id),
    FOREIGN KEY (player_id) REFERENCES nfl_raw.players(player_id)
);

