-- NFL Raw Data Tables Schema
-- This file contains the SQL schema for NFL raw data tables

-- Create schema for NFL raw data
CREATE SCHEMA IF NOT EXISTS nfl_raw;

-- Teams table
CREATE TABLE IF NOT EXISTS nfl_raw.teams (
    team_id VARCHAR(10) PRIMARY KEY,
    team_name VARCHAR(100) NOT NULL,
    team_abbreviation VARCHAR(10),
    team_conference VARCHAR(50),
    team_division VARCHAR(50),
    team_color VARCHAR(20),
    team_color_alt VARCHAR(20),
    team_logo VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Players table
CREATE TABLE IF NOT EXISTS nfl_raw.players (
    player_id VARCHAR(20) PRIMARY KEY,
    player_name VARCHAR(100) NOT NULL,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    position VARCHAR(10),
    height VARCHAR(10),
    weight INTEGER,
    birth_date DATE,
    college VARCHAR(100),
    draft_year INTEGER,
    draft_round INTEGER,
    draft_pick INTEGER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Games table
CREATE TABLE IF NOT EXISTS nfl_raw.games (
    game_id VARCHAR(20) PRIMARY KEY,
    season INTEGER NOT NULL,
    week INTEGER,
    season_type VARCHAR(20),
    game_date DATE,
    game_time TIME,
    home_team VARCHAR(10),
    away_team VARCHAR(10),
    home_score INTEGER,
    away_score INTEGER,
    home_win BOOLEAN,
    stadium VARCHAR(100),
    weather VARCHAR(100),
    temperature INTEGER,
    humidity INTEGER,
    wind_speed INTEGER,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

