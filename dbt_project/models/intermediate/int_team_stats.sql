-- Team defensive game stats (what the team allowed to opponents)
team_defense_game as (
    select
        g.game_id,
        g.season,
        g.game_date,
        tds.team_id,
        tds.opponent_team_id,
        tds.field_goals_made as fgm_allowed,
        tds.field_goals_attempted as fga_allowed,
        tds.three_pointers_made as three_pm_allowed,
        tds.three_pointers_attempted as three_pa_allowed,
        tds.free_throws_made as ftm_allowed,
        tds.free_throws_attempted as fta_allowed,
        tds.points as points_allowed,
        tds.offensive_rebounds as oreb_allowed,
        tds.defensive_rebounds as dreb_allowed,
        tds.assists as assists_allowed,
        tds.steals as steals_allowed,
        tds.blocks as blocks_allowed,
        tds.turnovers as turnovers_forced,
        tds.personal_fouls as fouls_committed,
        tda.off_rating as opp_off_rating,
        tda.def_rating as opp_def_rating,
        tda.net_rating as opp_net_rating,
        tda.e_off_rating as opp_e_off_rating,
        tda.e_def_rating as opp_e_def_rating,
        tda.e_net_rating as opp_e_net_rating,
        tda.ast_pct as opp_ast_pct,
        tda.ast_to as opp_ast_to,
        tda.ast_ratio as opp_ast_ratio,
        tda.oreb_pct as opp_oreb_pct,
        tda.dreb_pct as opp_dreb_pct,
        tda.reb_pct as opp_reb_pct,
        tda.tm_tov_pct as opp_tm_tov_pct,
        tda.e_tm_tov_pct as opp_e_tm_tov_pct,
        tda.efg_pct as opp_efg_pct,
        tda.ts_pct as opp_ts_pct,
        tda.usg_pct as opp_usg_pct,
        tda.e_usg_pct as opp_e_usg_pct,
        tda.e_pace as opp_e_pace,
        tda.pace as opp_pace,
        tda.pace_per40 as opp_pace_per40,
        tda.poss as opp_poss,
        tda.pie as opp_pie
    from team_def_box_scores tds
    join team_def_adv_box_scores tda on tds.game_id = tda.game_id and tds.team_id = tda.team_id
    join games g on g.game_id = tds.game_id
),

-- Team offensive game stats (what the team scored)
team_offensive_game as (
    select
        g.game_id,
        g.season,
        g.game_date,
        tbs.team_id,
        case when tbs.team_id = g.home_team_id then g.away_team_id else g.home_team_id end as opponent_team_id,
        tbs.field_goals_made as fgm_scored,
        tbs.field_goals_attempted as fga_scored,
        tbs.three_pointers_made as three_pm_scored,
        tbs.three_pointers_attempted as three_pa_scored,
        tbs.free_throws_made as ftm_scored,
        tbs.free_throws_attempted as fta_scored,
        tbs.points as points_scored,
        tbs.offensive_rebounds as oreb_scored,
        tbs.defensive_rebounds as dreb_scored,
        tbs.assists as assists_scored,
        tbs.steals as steals_scored,
        tbs.blocks as blocks_scored,
        tbs.turnovers as turnovers_committed,
        tbs.personal_fouls as fouls_drawn,
        tba.off_rating as team_off_rating,
        tba.def_rating as team_def_rating,
        tba.net_rating as team_net_rating,
        tba.e_off_rating as team_e_off_rating,
        tba.e_def_rating as team_e_def_rating,
        tba.e_net_rating as team_e_net_rating,
        tba.ast_pct as team_ast_pct,
        tba.ast_to as team_ast_to,
        tba.ast_ratio as team_ast_ratio,
        tba.oreb_pct as team_oreb_pct,
        tba.dreb_pct as team_dreb_pct,
        tba.reb_pct as team_reb_pct,
        tba.tm_tov_pct as team_tm_tov_pct,
        tba.e_tm_tov_pct as team_e_tm_tov_pct,
        tba.efg_pct as team_efg_pct,
        tba.ts_pct as team_ts_pct,
        tba.usg_pct as team_usg_pct,
        tba.e_usg_pct as team_e_usg_pct,
        tba.e_pace as team_e_pace,
        tba.pace as team_pace,
        tba.pace_per40 as team_pace_per40,
        tba.poss as team_poss,
        tba.pie as team_pie
    from team_box_scores tbs
    join team_advanced_box_scores tba on tbs.game_id = tba.game_id and tbs.team_id = tba.team_id
    join games g on g.game_id = tbs.game_id
),

